import AppKit
import LargeTextCore
import os

/// Live `PasteboardClient` over an `NSPasteboard` (`.general` in the app, a named board in tests).
@MainActor
package final class SystemPasteboardClient: PasteboardClient {
    /// nspasteboard.org markers. See http://nspasteboard.org
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let restoredType = NSPasteboard.PasteboardType("org.nspasteboard.RestoredType")

    private let pasteboard: NSPasteboard

    package init(pasteboard: NSPasteboard) {
        self.pasteboard = pasteboard
    }

    package var changeCount: Int { pasteboard.changeCount }

    /// Copies every item's data per type, skipping types rejected by `SnapshotTypeFilter`.
    /// Stops at the first type that would exceed `maxBytes` and marks the snapshot incomplete.
    package func snapshot(maxBytes: Int) -> PasteboardSnapshot {
        var items: [PasteboardSnapshot.Item] = []
        var totalBytes = 0
        var isComplete = true

        itemLoop: for item in pasteboard.pasteboardItems ?? [] {
            var dataByType: [String: Data] = [:]
            for type in item.types where SnapshotTypeFilter.shouldInclude(type.rawValue) {
                guard let data = item.data(forType: type) else { continue }
                guard totalBytes + data.count <= maxBytes else {
                    isComplete = false
                    if !dataByType.isEmpty { items.append(.init(dataByType: dataByType)) }
                    break itemLoop
                }
                totalBytes += data.count
                dataByType[type.rawValue] = data
            }
            if !dataByType.isEmpty { items.append(.init(dataByType: dataByType)) }
        }

        Logger.platform.info(
            "Pasteboard snapshot: \(items.count) items, \(totalBytes) bytes, complete=\(isComplete)"
        )
        return PasteboardSnapshot(items: items, isComplete: isComplete)
    }

    /// Replaces the pasteboard contents with the snapshot. Adds `org.nspasteboard.RestoredType` so
    /// clipboard managers can tell the restore apart from a fresh copy.
    package func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        let items = snapshot.items.map { snapshotItem -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in snapshotItem.dataByType {
                item.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
            return item
        }
        if let first = items.first {
            first.setData(Data(), forType: Self.restoredType)
            pasteboard.writeObjects(items)
        }
    }

    @discardableResult
    package func write(_ string: String, transient: Bool) -> Int {
        pasteboard.clearContents()
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        pasteboard.setString(string, forType: .string)
        if transient {
            pasteboard.setData(Data(), forType: Self.transientType)
            pasteboard.setData(Data(), forType: Self.autoGeneratedType)
        }
        return pasteboard.changeCount
    }
}
