import Foundation
import LargeTextCore

/// In-memory pasteboard with a `changeCount` that increments on every write and restore.
@MainActor
package final class FakePasteboard: PasteboardClient {
    nonisolated package static let stringType = "public.utf8-plain-text"
    nonisolated package static let transientType = "org.nspasteboard.TransientType"
    nonisolated package static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    package private(set) var items: [PasteboardSnapshot.Item]
    package private(set) var changeCount: Int
    package private(set) var snapshotCount = 0
    package private(set) var restoredSnapshots: [PasteboardSnapshot] = []
    package private(set) var writes: [(string: String, transient: Bool)] = []

    private let log: EventLog?

    package init(items: [PasteboardSnapshot.Item] = [], changeCount: Int = 0, log: EventLog? = nil) {
        self.items = items
        self.changeCount = changeCount
        self.log = log
    }

    /// Plain-text contents of the first item.
    package var string: String? {
        items.first?.dataByType[Self.stringType].flatMap { String(data: $0, encoding: .utf8) }
    }

    package var isTransient: Bool {
        items.first?.dataByType[Self.transientType] != nil
    }

    /// Keeps whole items in order until the byte budget is exhausted; the rest are dropped and the
    /// snapshot is marked incomplete.
    package func snapshot(maxBytes: Int) -> PasteboardSnapshot {
        snapshotCount += 1
        log?.append(.snapshot)
        var kept: [PasteboardSnapshot.Item] = []
        var used = 0
        for item in items {
            let size = item.dataByType.values.reduce(0) { $0 + $1.count }
            guard used + size <= maxBytes else {
                return PasteboardSnapshot(items: kept, isComplete: false)
            }
            used += size
            kept.append(item)
        }
        return PasteboardSnapshot(items: kept, isComplete: true)
    }

    package func restore(_ snapshot: PasteboardSnapshot) {
        restoredSnapshots.append(snapshot)
        log?.append(.restore)
        items = snapshot.items
        changeCount += 1
    }

    @discardableResult
    package func write(_ string: String, transient: Bool) -> Int {
        writes.append((string, transient))
        log?.append(.write(string, transient: transient))
        setString(string, transient: transient)
        return changeCount
    }

    /// Another app copying something: changes contents and `changeCount` without being logged.
    package func simulateExternalCopy(_ string: String) {
        setString(string, transient: false)
    }

    private func setString(_ string: String, transient: Bool) {
        var dataByType = [Self.stringType: Data(string.utf8)]
        if transient {
            dataByType[Self.transientType] = Data()
            dataByType[Self.autoGeneratedType] = Data()
        }
        items = [PasteboardSnapshot.Item(dataByType: dataByType)]
        changeCount += 1
    }
}

extension PasteboardSnapshot.Item {
    /// A plain-text item, for seeding a `FakePasteboard`.
    package static func text(_ string: String) -> PasteboardSnapshot.Item {
        PasteboardSnapshot.Item(dataByType: [FakePasteboard.stringType: Data(string.utf8)])
    }
}
