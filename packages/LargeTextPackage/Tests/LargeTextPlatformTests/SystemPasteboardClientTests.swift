import AppKit
import LargeTextCore
import Testing
@testable import LargeTextPlatform

/// Runs on a private named pasteboard, never `.general`.
@Suite @MainActor struct SystemPasteboardClientTests {
    let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    let restored = NSPasteboard.PasteboardType("org.nspasteboard.RestoredType")
    let custom = NSPasteboard.PasteboardType("com.example.largetext.custom")

    func withPasteboard(_ body: (NSPasteboard, SystemPasteboardClient) throws -> Void) rethrows {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("LargeText.tests.\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        try body(pasteboard, SystemPasteboardClient(pasteboard: pasteboard))
    }

    @Test func transientWriteAddsMarkersAndReturnsChangeCount() {
        withPasteboard { pasteboard, client in
            let before = client.changeCount
            let changeCount = client.write("hello", transient: true)
            #expect(changeCount == pasteboard.changeCount)
            #expect(changeCount > before)
            #expect(pasteboard.string(forType: .string) == "hello")
            let types = pasteboard.types ?? []
            #expect(types.contains(transient))
            #expect(types.contains(autoGenerated))
        }
    }

    @Test func nonTransientWriteHasNoMarkers() {
        withPasteboard { pasteboard, client in
            client.write("copy me", transient: false)
            #expect(pasteboard.string(forType: .string) == "copy me")
            let types = pasteboard.types ?? []
            #expect(!types.contains(transient))
            #expect(!types.contains(autoGenerated))
        }
    }

    @Test func writeReplacesPreviousContents() {
        withPasteboard { pasteboard, client in
            pasteboard.clearContents()
            pasteboard.setData(Data([1, 2, 3]), forType: custom)
            client.write("new", transient: true)
            #expect(pasteboard.data(forType: custom) == nil)
            #expect(pasteboard.string(forType: .string) == "new")
        }
    }

    @Test func snapshotAndRestoreRoundTripMultipleItems() throws {
        try withPasteboard { pasteboard, client in
            pasteboard.clearContents()
            let first = NSPasteboardItem()
            first.setString("original", forType: .string)
            first.setData(Data([0xDE, 0xAD]), forType: custom)
            let second = NSPasteboardItem()
            second.setString("second", forType: .string)
            #expect(pasteboard.writeObjects([first, second]))

            let snapshot = client.snapshot(maxBytes: 1_000_000)
            #expect(snapshot.isComplete)
            #expect(snapshot.items.count == 2)
            #expect(snapshot.items[0].dataByType[NSPasteboard.PasteboardType.string.rawValue] == Data("original".utf8))
            #expect(snapshot.items[0].dataByType[custom.rawValue] == Data([0xDE, 0xAD]))
            #expect(!snapshot.items.flatMap(\.dataByType.keys).contains { $0.hasPrefix("dyn.") })

            client.write("inserted", transient: true)
            #expect(pasteboard.string(forType: .string) == "inserted")

            client.restore(snapshot)
            let items = try #require(pasteboard.pasteboardItems)
            #expect(items.count == 2)
            #expect(items[0].string(forType: .string) == "original")
            #expect(items[0].data(forType: custom) == Data([0xDE, 0xAD]))
            #expect(items[0].types.contains(restored))
            #expect(items[1].string(forType: .string) == "second")
            #expect(!(pasteboard.types ?? []).contains(transient))
        }
    }

    @Test func snapshotOverBudgetIsIncomplete() {
        withPasteboard { pasteboard, client in
            pasteboard.clearContents()
            let small = NSPasteboardItem()
            small.setData(Data(count: 10), forType: custom)
            let large = NSPasteboardItem()
            large.setData(Data(count: 1_000), forType: custom)
            pasteboard.writeObjects([small, large])

            let snapshot = client.snapshot(maxBytes: 100)
            #expect(!snapshot.isComplete)
            #expect(snapshot.items.count == 1)
            #expect(snapshot.items[0].dataByType[custom.rawValue]?.count == 10)
        }
    }

    @Test func emptyPasteboardSnapshotRestoresToEmpty() {
        withPasteboard { pasteboard, client in
            pasteboard.clearContents()
            let snapshot = client.snapshot(maxBytes: 100)
            #expect(snapshot == PasteboardSnapshot(items: [], isComplete: true))

            client.write("temp", transient: true)
            client.restore(snapshot)
            #expect((pasteboard.pasteboardItems ?? []).isEmpty)
        }
    }
}
